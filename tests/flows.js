const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message + '\n' + e.stack));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('file://' + path.resolve('game.html'));
  await page.waitForTimeout(400);
  const S = () => page.evaluate(() => ({ s: window.__echoform.G.state, t: +window.__echoform.G.vt.toFixed(2), ctx: window.__echoform.audio.ctx && window.__echoform.audio.ctx.state, app: window.__echoform.G.approach }));
  await page.click('#btn-settings');
  await page.click('#btn-calibrate');
  console.log('cal open', JSON.stringify(await S()));
  const t0 = Date.now();
  for (let i = 0; i < 18; i++) {
    const target = 800 + i * 600 + 30;
    const wait = target - (Date.now() - t0);
    if (wait > 0) await page.waitForTimeout(wait);
    await page.keyboard.press('Space');
  }
  await page.waitForTimeout(1500);
  console.log('cal read:', await page.textContent('#cal-read'));
  console.log('apply enabled:', !(await page.isDisabled('#btn-cal-apply')));
  await page.click('#btn-cal-apply');
  console.log('offset now', await page.evaluate(() => window.__echoform.settings.offsetMs), 'state', (await S()).s);
  await page.evaluate(() => { window.__echoform.settings.offsetMs = 0; });
  await page.click('#btn-settings-done');
  await page.setInputFiles('#file-input', path.resolve('hiphop88.wav'));
  await page.waitForFunction(() => window.__echoform.G.state === 'ready');
  const b0 = await page.evaluate(() => window.__echoform.G.song.analysis.beats[1]);
  await page.click('#btn-shift');
  const b1 = await page.evaluate(() => ({ b: window.__echoform.G.song.analysis.beats[1], shifted: window.__echoform.G.song.analysis.shifted, notes: window.__echoform.G.chart.notes.length, label: document.querySelector('#btn-shift').textContent }));
  await page.click('#btn-shift');
  const b2 = await page.evaluate(() => ({ b: window.__echoform.G.song.analysis.beats[1], shifted: !!window.__echoform.G.song.analysis.shifted }));
  console.log('shift', b0.toFixed(3), JSON.stringify(b1), JSON.stringify(b2));
  await page.click('#load-ready [data-diff="chill"]');
  console.log('chill notes', await page.evaluate(() => window.__echoform.G.chart.notes.length), await page.textContent('#load-stats'));
  await page.keyboard.press('Space');
  await page.waitForTimeout(3500);
  console.log('playing', JSON.stringify(await S()));
  await page.keyboard.press('Escape');
  await page.waitForTimeout(300);
  console.log('paused', JSON.stringify(await S()));
  await page.waitForTimeout(700);
  console.log('still paused', JSON.stringify(await S()));
  await page.click('#btn-pause-settings');
  console.log('calibrate hidden in pause:', await page.isHidden('#btn-calibrate'));
  await page.fill('#s-speed', '1.5');
  await page.dispatchEvent('#s-speed', 'input');
  await page.click('#btn-settings-done');
  console.log('back to', JSON.stringify(await S()));
  await page.keyboard.press('Escape');
  await page.waitForTimeout(2200);
  console.log('resumed', JSON.stringify(await S()));
  await page.waitForTimeout(1000);
  console.log('advancing', JSON.stringify(await S()));
  await page.keyboard.press('Escape');
  await page.click('#btn-quit');
  console.log('quit', JSON.stringify(await S()));
  console.log('ERRORS', errors.length ? errors.join('\n') : 'none');
  await browser.close();
})();
